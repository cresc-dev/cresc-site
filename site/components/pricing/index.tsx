const compactFormatter = new Intl.NumberFormat("en-US", {
  notation: "compact",
  maximumFractionDigits: 0,
});

function formatSize(size: string) {
  const amount = Number.parseInt(size, 10);

  if (!Number.isFinite(amount)) {
    return size.toUpperCase();
  }

  if (amount >= 1000) {
    const gigabytes = amount / 1000;
    return Number.isInteger(gigabytes)
      ? `${gigabytes} GB`
      : `${gigabytes.toFixed(1)} GB`;
  }

  return `${amount} MB`;
}

function formatQueries(value: number) {
  return `${compactFormatter.format(value)} / day`;
}

function formatQuota(count: number, noun: string, size: string) {
  return `${count} ${noun} · ${formatSize(size)} ea`;
}

function QueryValue({
  value,
}: {
  value: number;
}) {
  return (
    <div className="min-w-[8.6rem] text-right text-[1.45rem] font-semibold leading-none tracking-tight text-[#b45309] sm:text-[1.55rem]">
      <span className="block">
        {formatQueries(value)}
      </span>
    </div>
  );
}

function formatMetricValue(
  tierKey: TierKey,
  kind: "app" | "package" | "bundle",
  quota: TierQuota,
) {
  if ((tierKey === "max" || tierKey === "ultra") && kind !== "app") {
    return "Same limits as Pro";
  }

  if ((tierKey === "max" || tierKey === "ultra") && kind === "app") {
    return "Same limits as Pro";
  }

  if (kind === "app") {
    return `${quota.app} apps`;
  }

  if (kind === "package") {
    return `${quota.package} base pkgs`;
  }

  return formatQuota(quota.bundle, "updates", quota.bundleSize);
}

